"""Emit decided actor addresses and field writes; no game installation is read."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
MANIFEST=ROOT/'chriz-sod-remix/data/area-actor-ownership.json'
XP={220:('csr_xp_chunk',106700),230:('csr_xp_chunk_230',23100),260:('csr_xp_chunk_260',103600),270:('csr_xp_chunk_270',5200)}
def render(component):
    areas=json.loads(MANIFEST.read_text(encoding='utf-8'))[str(component)]
    lines=['// Authored actor-field ownership; generated by build_area_ownership.py.', '// Duplicate labels use their native occurrence as a record address.', 'INCLUDE ~chriz-sod-remix/lib/overwrite_actors.tpa~','']
    for area,rows in areas.items():
        lines += ['ACTION_CLEAR_ARRAY csr_actor_fields','ACTION_DEFINE_ASSOCIATIVE_ARRAY csr_actor_fields BEGIN']
        for row in rows:
            fields=[row['name'],row['ordinal'],1 if 'cut' in row else 0,row.get('mvx',0),row.get('mvy',0),row.get('mvo',0),row.get('fallback',''),row.get('created_name','')]
            lines.append('  '+', '.join('~'+str(v)+'~' for v in fields)+' => 1')
        lines += ['END',f'LAF csr_write_area_actors STR_VAR area = ~{area}~ END','']
    if component in XP:
        key,value=XP[component];lines += [f'OUTER_SET {key} = {value}','']
    return '\n'.join(lines)
def emit(*components):
    for component in components:
        path=ROOT/f'chriz-sod-remix/lib/comp{component}_lists.tpa'
        path.write_bytes(render(component).replace('\n','\r\n').encode('utf-8'))
        print(path.relative_to(ROOT))
if __name__=='__main__':
    import sys
    emit(*(map(int,sys.argv[1:]) if sys.argv[1:] else (200,220,230,260,270)))
