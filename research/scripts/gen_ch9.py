"""Emit the decided chapter-nine actors and XP, without reading game data."""
import json
from build_area_ownership import ROOT, emit

def main():
    emit(230)
    spec=json.loads((ROOT/'chriz-sod-remix/data/area240-ownership.json').read_text())
    lines=['// Authored optional-loop actor removals. Generated by gen_ch9.py.']
    for area,names in spec.items():
        for name in names:lines.append(f'OUTER_SPRINT $csr_cut_{area}(~{name}~) ~1~')
        lines.append(f'OUTER_SET csr_cutn_{area} = {len(names)}')
    lines += ['OUTER_SET csr_xp_chunk_240 = 22700','']
    (ROOT/'chriz-sod-remix/lib/comp240_lists.tpa').write_bytes('\r\n'.join(lines).encode())
if __name__=='__main__': main()
